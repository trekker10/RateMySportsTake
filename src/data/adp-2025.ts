/**
 * Look up a player's 2025 ADP by name.
 * Tries exact match first, then partial/fuzzy match.
 */
export function getAdp2025(playerName: string): number | null {
  const needle = playerName.toLowerCase().trim();

  // Exact match
  if (ADP_2025[needle] !== undefined) return ADP_2025[needle];

  // Partial match — find first entry where one contains the other
  for (const [key, adp] of Object.entries(ADP_2025)) {
    if (key.includes(needle) || needle.includes(key)) return adp;
  }

  // Last-name-only fallback (e.g. "Barkley" → "saquon barkley")
  const lastName = needle.split(" ").pop() ?? "";
  if (lastName.length > 3) {
    for (const [key, adp] of Object.entries(ADP_2025)) {
      if (key.endsWith(lastName)) return adp;
    }
  }

  return null;
}
